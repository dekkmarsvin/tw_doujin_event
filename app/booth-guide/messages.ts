export const GUIDE_MESSAGES = defineMessages({
  "zh-Hant": Object.fromEntries(rows.map(([zh]) => [zh, zh])),
  en: Object.fromEntries(rows.map(([zh, en]) => [zh, en])),
  ja: Object.fromEntries(rows.map(([zh, , ja]) => [zh, ja])),
});
export function useGuideText() {
  const { locale } = useLocale();
  return useCallback((text: string, params?: MessageParams) =>
    Object.hasOwn(GUIDE_MESSAGES["zh-Hant"], text) ? translate(GUIDE_MESSAGES, locale, text, params) : text, [locale]);
}
